using System;
using System.Collections.Generic;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace PetWAMS.Web.Models
{
    [Table("PetShopOrders")]
    public class PetShopOrder
    {
        [Key]
        public int OrderID { get; set; }

        [Required]
        public int UserID { get; set; }

        [Required]
        [StringLength(60)]
        public string OrderNumber { get; set; } = string.Empty;

        [Column(TypeName = "decimal(18,2)")]
        public decimal TotalAmount { get; set; }

        [StringLength(40)]
        public string PaymentMethod { get; set; } = "Demo Payment";

        [StringLength(30)]
        public string PaymentStatus { get; set; } = "Paid";


        // =====================================================
        // REFUND INFORMATION
        // =====================================================

        [StringLength(30)]
        public string RefundStatus { get; set; } = "None";

        [Column(TypeName = "decimal(18,2)")]
        public decimal RefundAmount { get; set; } = 0;

        public DateTime? RefundCompletedAt { get; set; }

        [StringLength(300)]
        public string? RefundNote { get; set; }


        // =====================================================
        // REAL SSLCOMMERZ REFUND INFORMATION
        // =====================================================

        // Unique refund transaction ID generated by PetHope.
        // This is sent to SSLCommerz as refund_trans_id.
        [StringLength(60)]
        public string? RefundTransactionID { get; set; }


        // SSLCommerz returns this after refund initiation.
        // Later this ID is used to query actual refund status.
        [StringLength(100)]
        public string? RefundReferenceID { get; set; }


        // success / processing / refunded / failed / cancelled
        [StringLength(30)]
        public string? RefundGatewayStatus { get; set; }


        // Any message/error returned by SSLCommerz refund API.
        [StringLength(500)]
        public string? RefundGatewayMessage { get; set; }


        // When refund request was actually sent to SSLCommerz.
        public DateTime? RefundInitiatedAt { get; set; }


        // Last time refund status was checked from SSLCommerz.
        public DateTime? RefundLastCheckedAt { get; set; }


        // =====================================================
        // ORDER INFORMATION
        // =====================================================

        [StringLength(30)]
        public string OrderStatus { get; set; } = "Pending";

        [StringLength(30)]
        public string DeliveryStatus { get; set; } = "Not Shipped";


        // =====================================================
        // SSLCOMMERZ PAYMENT INFORMATION
        // =====================================================

        [StringLength(80)]
        public string? TransactionID { get; set; }

        [StringLength(100)]
        public string? SessionKey { get; set; }

        [StringLength(1000)]
        public string? GatewayPageURL { get; set; }

        [StringLength(100)]
        public string? ValidationID { get; set; }

        [StringLength(120)]
        public string? BankTransactionID { get; set; }

        [StringLength(120)]
        public string? CardType { get; set; }

        [StringLength(150)]
        public string? CardIssuer { get; set; }

        [StringLength(80)]
        public string? CardBrand { get; set; }

        [StringLength(30)]
        public string? GatewayStatus { get; set; }

        [Column(TypeName = "decimal(18,2)")]
        public decimal? StoreAmount { get; set; }

        public int? RiskLevel { get; set; }

        [StringLength(100)]
        public string? RiskTitle { get; set; }

        public DateTime? PaymentInitiatedAt { get; set; }

        public DateTime? PaymentValidatedAt { get; set; }


        // =====================================================
        // CANCELLATION POLICY
        // =====================================================

        public bool CancellationRequested { get; set; } = false;

        [StringLength(30)]
        public string CancellationStatus { get; set; } = "None";

        [StringLength(400)]
        public string? CancellationReason { get; set; }


        // =====================================================
        // CUSTOMER DELIVERY INFORMATION
        // =====================================================

        [StringLength(120)]
        public string? CustomerName { get; set; }

        [StringLength(30)]
        public string? Phone { get; set; }

        [StringLength(350)]
        public string? DeliveryAddress { get; set; }


        // =====================================================
        // DATES
        // =====================================================

        public DateTime OrderDate { get; set; } = DateTime.Now;

        public DateTime? ConfirmedAt { get; set; }

        public DateTime? CancelledAt { get; set; }

        public DateTime? DeliveredAt { get; set; }


        // =====================================================
        // RELATIONSHIPS
        // =====================================================

        [ForeignKey("UserID")]
        public User? User { get; set; }

        public ICollection<PetShopOrderItem> OrderItems { get; set; }
            = new List<PetShopOrderItem>();
    }
}